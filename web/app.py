# ---------- helpers ----------

def _env(name: str, default: str = "") -> str:
    return os.environ.get(name, default)


def _public_host() -> str:
    # Railway → RAILWAY_PUBLIC_DOMAIN. Можно переопределить PUBLIC_HOST.
    return (
        _env("PUBLIC_HOST")
        or _env("RAILWAY_PUBLIC_DOMAIN")
        or request.host.split(":")[0]
    )


def _sub_prefix() -> str:
    return _env("SUB_PATH", "").rstrip("/")


def _vless_link(host: str) -> str:
    uuid = _env("VLESS_UUID")
    ws_path = _env("WS_PATH", "/")
    profile = _env("PROFILE_NAME", "Railway-VPN")

    params = {
        "type": "ws",
        "security": "tls",
        "sni": host,
        "host": host,
        "path": ws_path,
        "encryption": "none",
        "fp": "chrome",
        "alpn": "h2,http/1.1",
    }
    qs = urlencode(params, safe="/:")
    return f"vless://{uuid}@{host}:443?{qs}#{quote(profile)}"


