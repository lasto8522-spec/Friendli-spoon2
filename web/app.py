def _check_auth(username: str, password: str) -> bool:
    expected_user = _env("BASIC_AUTH_USER", "admin")
    expected_pass = _env("BASIC_AUTH_PASS", "")
    if not expected_pass:
        return False
    return secrets.compare_digest(username, expected_user) and secrets.compare_digest(
        password, expected_pass
    )


def _auth_required():
    return Response(
        "Authentication required",
        401,
        {"WWW-Authenticate": 'Basic realm="VPN config"'},
    )


def basic_auth(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        auth = request.authorization
        if not auth or not _check_auth(auth.username or "", auth.password or ""):
            return _auth_required()
        return fn(*args, **kwargs)

    return wrapper


# ---------- routes ----------

@app.get("/healthz")
def healthz():  # вызывается Caddy / Railway healthcheck
    return "ok", 200


@app.get(f"{_sub_prefix() or ''}/")
@basic_auth
def dashboard():
    host = _public_host()
    link = _vless_link(host)
    pref = _sub_prefix()
    return render_template(
        "config.html",
        link=link,
        sub_url=f"https://{host}{pref}/sub",
        clash_url=f"https://{host}{pref}/clash",
        host=host,
        qr_url=f"{pref}/qr.png",
        raw_url=f"{pref}/raw",
        profile=_env("PROFILE_NAME", "Railway-VPN"),
    )


@app.get(f"{_sub_prefix() or ''}/raw")
@basic_auth
def raw():
    return Response(_vless_link(_public_host()) + "\n", mimetype="text/plain")


@app.get(f"{_sub_prefix() or ''}/qr.png")
@basic_auth
def qr_png():
    link = _vless_link(_public_host())
    img = qrcode.make(link, box_size=8, border=2)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return Response(buf.read(), mimetype="image/png")


@app.get(f"{_sub_prefix() or ''}/sub")
def subscription():
    """
    Эндпоинт подписки v2ray-формата (base64 со списком vless://).
    Понимают v2rayN, v2rayNG, NekoBox, Streisand.
    Basic-Auth НЕ ставим (мобильные клиенты не умеют его в подписке),
    безопасность держится на длинном случайном ${SUB_PATH}.
    """
    payload = _vless_link(_public_host()) + "\n"
    encoded = base64.b64encode(payload.encode()).decode()
    resp = Response(encoded, mimetype="text/plain; charset=utf-8")
    resp.headers["Profile-Update-Interval"] = "24"
    resp.headers["Subscription-Userinfo"] = "upload=0; download=0; total=0; expire=0"
    return resp


@app.get(f"{_sub_prefix() or ''}/clash")
def clash_subscription():
    """
    Подписка в формате Mihomo/Clash.Meta с готовыми правилами split-routing:
    российские сервисы идут DIRECT, всё остальное — через VPN.
    Понимают Hiddify, Mihomo Party, Stash, ClashX Meta, v2rayN (Pro).
    """
    body = _clash_yaml(_public_host())
    resp = Response(body, mimetype="text/yaml; charset=utf-8")
    resp.headers["Content-Disposition"] = (
        f'inline; filename="{_env("PROFILE_NAME", "Railway-VPN")}.yaml"'
    )
    resp.headers["Profile-Update-Interval"] = "24"
    resp.headers["Subscription-Userinfo"] = "upload=0; download=0; total=0; expire=0"
    return resp


# Fallback на корень — чтобы не было 404 при пустом ${SUB_PATH}.
if _sub_prefix():
    @app.get("/")
    def _root_redirect():
        # На корне Flask отвечать не должен — Caddy его не маршрутизирует сюда,
        # но если кто-то залез — притворимся 404.
        abort(404)


if __name__ == "__main__":
    # bind только на loopback — наружу торчит только Caddy.
    # Порт берём из FLASK_PORT, чтобы не конфликтовать с Railway $PORT,
    # на котором висит Caddy.
    port = int(os.environ.get("FLASK_PORT", "10001"))
    app.run(host="127.0.0.1", port=port, threaded=True)
